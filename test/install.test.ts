posix("stableNode returns the first node on PATH that resolves to this binary", () => {
  const home = temporaryHome();
  const other = join(home, "other");
  const linked = join(home, "linked");
  const second = join(home, "second");
  for (const directory of [other, linked, second]) mkdirSync(directory);
  writeFileSync(join(other, "node"), "#!/bin/sh\n");
  chmodSync(join(other, "node"), 0o755);
  symlinkSync(process.execPath, join(linked, "node"));
  symlinkSync(process.execPath, join(second, "node"));
  vi.stubEnv("PATH", ["", other, join(home, "missing"), linked, second].join(delimiter));
  expect(stableNode()).toBe(join(linked, "node"));
});

test("stableNode falls back to process.execPath when no node on PATH is this binary, or PATH is unset", () => {
  const home = temporaryHome();
  vi.stubEnv("PATH", join(home, "missing"));
  expect(stableNode()).toBe(process.execPath);
  vi.stubEnv("PATH", undefined);
  expect(stableNode()).toBe(process.execPath);
});
