const root = join(import.meta.dirname, "..");
const pluginSource = join(root, "plugin");
const { version } = JSON.parse(readFileSync(join(root, "package.json"), "utf8")) as {
  version: string;
};
const npx = `npx -y cheap-agent@${version}`;
const posix = test.skipIf(process.platform === "win32");

/** A temporary home: HOME, USERPROFILE and every XDG folder point inside it, so nothing reaches the real home. */
function temporaryHome() {
  const home = realpathSync.native(mkdtempSync(join(tmpdir(), "cheapag-install-")));
  onTestFinished(() => rmSync(home, { recursive: true, force: true }));
  vi.stubEnv("HOME", home);
  vi.stubEnv("USERPROFILE", home);
  vi.stubEnv("XDG_CONFIG_HOME", join(home, "config"));
  vi.stubEnv("XDG_DATA_HOME", join(home, "data"));
  vi.stubEnv("XDG_CACHE_HOME", join(home, "cache"));
  vi.stubEnv("XDG_STATE_HOME", join(home, "state"));
  onTestFinished(() => void vi.unstubAllEnvs());
  return home;
}

/** Every file under `directory`, as sorted forward-slash paths relative to it. */
function listFiles(directory: string): string[] {
  const entries = readdirSync(directory, { recursive: true, withFileTypes: true });
  const files = entries.filter((entry) => entry.isFile());
  const paths = files.map((entry) =>
    normalisePath(relative(directory, join(entry.parentPath, entry.name))),
  );
  return paths.sort();
}

/** The launcher text, written out in full so any change to it fails here. */
function expectedLauncher(entry: string) {
  return `// cheapag: gates the guard hook, runs this install, else the fallback npx -y cheap-agent@${version}
"use strict";
const { execFileSync, spawnSync } = require("node:child_process");
const { existsSync } = require("node:fs");
const { join } = require("node:path");
const { pathToFileURL } = require("node:url");
const entry = ${JSON.stringify(entry)};
if (process.argv[2] === "hook" && process.argv[3] === "guard") {
  let root;
  try {
    root = execFileSync("git", ["rev-parse", "--show-toplevel"], { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
  } catch {
    process.exit(0);
  }
  if (!existsSync(join(root, ".cheapag", "hook.json")) && !existsSync(join(root, ".cheapag", "hook", "takeover"))) process.exit(0);
}
if (existsSync(entry)) {
  process.argv[1] = entry;
  import(pathToFileURL(entry).href);
} else {
  const r = spawnSync("npx", ["-y", "cheap-agent@${version}", ...process.argv.slice(2)], { stdio: "inherit", shell: process.platform === "win32" });
  process.exit(r.status ?? 1);
}
`;
}

const expectedManifest = `{
  "name": "cheapag",
  "owner": {
    "name": "muaaz9329"
  },
  "description": "Cheap Agent, generated by its setup from the installed package",
  "plugins": [
    {
      "name": "cheapag",
      "source": "./cheapag",
      "description": "Claude plans, a cheap model writes the code"
    }
  ]
}
`;

const sourceFiles = listFiles(pluginSource);
const rewritten = (file: string) => file.endsWith("SKILL.md") || file === "hooks/hooks.json";

test("MARKETPLACE is cheapag, and installPaths sit next to the user config", () => {
  const home = temporaryHome();
  expect(MARKETPLACE).toBe("cheapag");
  expect(installPaths()).toEqual({
    launcher: join(home, "config", "cheapag", "bin", "cheapag.cjs"),
    marketplace: join(home, "config", "cheapag", "marketplace"),
  });
});

test("installPaths falls back to ~/.config when XDG_CONFIG_HOME is empty", () => {
  const home = temporaryHome();
  vi.stubEnv("XDG_CONFIG_HOME", "");
  expect(installPaths()).toEqual({
    launcher: join(home, ".config", "cheapag", "bin", "cheapag.cjs"),
    marketplace: join(home, ".config", "cheapag", "marketplace"),
  });
});

test("writePlugin on POSIX writes the launcher, rewrites only SKILL.md and hooks.json, and its own marketplace", () => {
  temporaryHome();
  const entry = join(tmpdir(), "somewhere", "dist", "index.js");
  const { launcher, marketplace } = installPaths();
  expect(writePlugin(entry, "/unused/node", "linux")).toBe(marketplace);

  expect(readFileSync(launcher, "utf8")).toBe(expectedLauncher(entry));
  const plugin = join(marketplace, "cheapag");
  const copied = sourceFiles.filter((file) => file !== ".mcp.json");
  expect(listFiles(marketplace)).toEqual(
    [".claude-plugin/marketplace.json", ...copied.map((file) => `cheapag/${file}`)].sort(),
  );
  const command = `node '${launcher}'`;
  for (const file of copied) {
    const source = readFileSync(join(pluginSource, file), "utf8");
    const expected = rewritten(file) ? source.replaceAll(npx, command) : source;
    expect(readFileSync(join(plugin, file), "utf8"), file).toBe(expected);
  }
  const allow = readFileSync(join(plugin, "skills", "allow", "SKILL.md"), "utf8");
  expect(allow).toContain(`allowed-tools: Bash(${command} allow) Bash(${command} allow *)`);
  const hooks = readFileSync(join(plugin, "hooks", "hooks.json"), "utf8");
  expect(hooks).toContain(
    `"command": "r=$(git rev-parse --show-toplevel 2>/dev/null) && { [ -f \\"$r/.cheapag/hook.json\\" ] || [ -f \\"$r/.cheapag/hook/takeover\\" ]; } && ${command} hook guard; exit 0"`,
  );
  expect(readFileSync(join(marketplace, ".claude-plugin", "marketplace.json"), "utf8")).toBe(
    expectedManifest,
  );
});

test("writePlugin replaces the whole marketplace on every run, so stale files go", () => {
  temporaryHome();
  const { marketplace } = installPaths();
  mkdirSync(join(marketplace, "cheapag"), { recursive: true });
  writeFileSync(join(marketplace, "stale.txt"), "old");
  writeFileSync(join(marketplace, "cheapag", "old.json"), "{}");
  writePlugin(join(tmpdir(), "index.js"), "/unused/node", "darwin");
  const files = listFiles(marketplace);
  expect(files).not.toContain("stale.txt");
  expect(files).not.toContain("cheapag/old.json");
  expect(files).toContain(".claude-plugin/marketplace.json");
});

test("writePlugin on win32 rewrites hooks.json as two-space JSON and quotes the launcher with double quotes", () => {
  temporaryHome();
  const entry = join(tmpdir(), "win", "index.js");
  const { launcher, marketplace } = installPaths();
  expect(writePlugin(entry, "/unused/node", "win32")).toBe(marketplace);

  expect(readFileSync(launcher, "utf8")).toBe(expectedLauncher(entry));
  const command = `node "${normalisePath(launcher)}"`;
  const hooks = JSON.parse(readFileSync(join(pluginSource, "hooks", "hooks.json"), "utf8"));
  hooks.hooks.PreToolUse[0].hooks[0].command = `${command} hook guard`;
  hooks.hooks.PostToolUse[0].hooks[0].command = `${command} hook result`;
  hooks.hooks.SessionStart[0].hooks[0].command = `${command} hook context`;
  const plugin = join(marketplace, "cheapag");
  expect(readFileSync(join(plugin, "hooks", "hooks.json"), "utf8")).toBe(
    JSON.stringify(hooks, null, 2) + "\n",
  );
  for (const file of sourceFiles.filter((name) => name.endsWith("SKILL.md"))) {
    const source = readFileSync(join(pluginSource, file), "utf8");
    expect(readFileSync(join(plugin, file), "utf8"), file).toBe(source.replaceAll(npx, command));
  }
  expect(readFileSync(join(marketplace, ".claude-plugin", "marketplace.json"), "utf8")).toBe(
    expectedManifest,
  );
});

/**
 * Puts a fake `claude` alone on PATH. It logs each call's arguments, and `cases` are sh case arms on "$*" that decide
 * what it prints and its exit code (default: nothing, exit 0). Returns the log reader.
 */
function fakeClaude(home: string, cases: string[] = []) {
  const bin = join(home, "bin");
  const log = join(home, "claude-calls.log");
  mkdirSync(bin, { recursive: true });
  const script = [
    "#!/bin/sh",
    `printf '%s\\n' "$*" >> '${log}'`,
    'case "$*" in',
    ...cases.map((arm) => `  ${arm} ;;`),
    "esac",
    "exit 0",
    "",
  ].join("\n");
  writeFileSync(join(bin, "claude"), script);
  chmodSync(join(bin, "claude"), 0o755);
  vi.stubEnv("PATH", bin);
  return () => readFileSync(log, "utf8").trim().split("\n");
}

/** Runs installPlugin, collecting what it prints. */
function runInstall(options?: { update?: boolean }) {
  const lines: (string | undefined)[] = [];
  const ok = installPlugin((line) => lines.push(line), options);
  return { ok, lines };
}

const LISTED_MARKETPLACE = `'plugin marketplace list') echo '  ❯ cheapag'`;
const LISTED_PLUGIN = `'plugin list') echo '  ❯ cheapag@cheapag'`;

posix(
  "installPlugin on a machine without the plugin adds the marketplace, installs, and says so",
  () => {
    const home = temporaryHome();
    const calls = fakeClaude(home);
    const { launcher, marketplace } = installPaths();
    expect(runInstall()).toEqual({
      ok: true,
      lines: ["✓ Added the cheapag plugin to Claude Code (its /cheapag commands and hooks)"],
    });
    expect(calls()).toEqual([
      "plugin marketplace list",
      "plugin list",
      `plugin marketplace add ${marketplace}`,
      "plugin install cheapag@cheapag",
    ]);
    // the launcher runs the script this process was started with
    expect(readFileSync(launcher, "utf8")).toBe(expectedLauncher(realpathSync(process.argv[1])));
  },
);

posix("installPlugin updates what is listed, and with update: true names the version", () => {
  const home = temporaryHome();
  const calls = fakeClaude(home, [LISTED_MARKETPLACE, LISTED_PLUGIN]);
  expect(runInstall({ update: true })).toEqual({
    ok: true,
    lines: [`✓ Updated the cheapag plugin to ${version}`],
  });
  expect(calls()).toEqual([
    "plugin marketplace list",
    "plugin list",
    "plugin marketplace update cheapag",
    "plugin update cheapag@cheapag",
  ]);
});

posix("installPlugin updates a listed marketplace but installs a missing plugin", () => {
  const home = temporaryHome();
  const calls = fakeClaude(home, [LISTED_MARKETPLACE]);
  expect(runInstall({ update: false })).toEqual({
    ok: true,
    lines: ["✓ Added the cheapag plugin to Claude Code (its /cheapag commands and hooks)"],
  });
  expect(calls()).toEqual([
    "plugin marketplace list",
    "plugin list",
    "plugin marketplace update cheapag",
    "plugin install cheapag@cheapag",
  ]);
});

posix("a failed step prints its first error line and the manual commands, and stops there", () => {
  const home = temporaryHome();
  const calls = fakeClaude(home, [
    `'plugin marketplace add '*) printf 'boom\\nmore\\n' >&2; echo out; exit 1`,
  ]);
  const { marketplace } = installPaths();
  expect(runInstall()).toEqual({
    ok: false,
    lines: [
      `✗ claude plugin marketplace add ${marketplace} failed (boom). Run these yourself:`,
      `  claude plugin marketplace add ${marketplace}\n  claude plugin install cheapag@cheapag`,
    ],
  });
  expect(calls()).toEqual([
    "plugin marketplace list",
    "plugin list",
    `plugin marketplace add ${marketplace}`,
  ]);
});

posix(
  "a failed step with no stderr shows its stdout, and with no output shows empty brackets",
  () => {
    const home = temporaryHome();
    fakeClaude(home, [
      `'plugin update cheapag@cheapag') echo 'no such plugin'; exit 2`,
      LISTED_PLUGIN,
    ]);
    const { marketplace } = installPaths();
    expect(runInstall({ update: true })).toEqual({
      ok: false,
      lines: [
        "✗ claude plugin update cheapag@cheapag failed (no such plugin). Run these yourself:",
        `  claude plugin marketplace add ${marketplace}\n  claude plugin install cheapag@cheapag`,
      ],
    });

    fakeClaude(home, [`'plugin install cheapag@cheapag') exit 1`]);
    expect(runInstall().lines[0]).toBe(
      "✗ claude plugin install cheapag@cheapag failed (). Run these yourself:",
    );
  },
);

